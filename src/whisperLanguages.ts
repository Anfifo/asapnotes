/** How many of the list lead as the common picks before the alphabetical rest. */
export const COMMON_LANGUAGES = 3;

const names = new Intl.DisplayNames(undefined, { type: "language" });

/** The language's name in the UI locale; the code itself when the platform
 * has no name for it (a few of the rarer ones). */
export function languageName(code: string): string {
  try {
    const name = names.of(code);
    return name && name !== code ? name : code;
  } catch {
    return code;
  }
}
